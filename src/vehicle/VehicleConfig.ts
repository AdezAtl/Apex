export interface VehicleHandlingConfig {
  /** Maximum forward speed in meters per second (42 m/s ≈ 151 km/h) */
  maxForwardSpeed: number;
  /** Maximum reverse speed in meters per second (12 m/s ≈ 43 km/h) */
  maxReverseSpeed: number;
  /** Forward acceleration force in m/s² */
  acceleration: number;
  /** Service braking deceleration rate in m/s² */
  brakeForce: number;
  /** Reverse acceleration in m/s² */
  reverseAcceleration: number;
  /** Natural rolling resistance / engine braking deceleration when off-throttle in m/s² */
  engineBraking: number;
  /** Aerodynamic drag coefficient proportional to velocity squared */
  aerodynamicDrag: number;
  /** Steering angle transition rate in radians per second */
  steerRate: number;
  /** Maximum front wheel steering angle at low speed in radians (0.55 rad ≈ 31.5°) */
  maxSteerAngle: number;
  /** Steering sensitivity multiplier applied at maximum vehicle speed (0.35 = 65% reduction) */
  highSpeedSteerReduction: number;
  /** Normal lateral grip coefficient resisting sideways slide */
  normalLateralGrip: number;
  /** Grip multiplier applied to rear wheels when handbrake is engaged */
  handbrakeGripMultiplier: number;
  /** Grip coefficient when actively sliding / drifting */
  driftSlipGrip: number;
  /** Rate at which lateral slip velocity converts back to forward traction */
  lateralDamping: number;
  /** Yaw angular acceleration generated by steering input */
  yawResponse: number;
  /** Rotational inertia damping to prevent endless spinning */
  yawDamping: number;
  /** Stability assistance factor when player counter-steers into a slide */
  counterSteerAssist: number;
  /** Effective tire radius in meters used for wheel rotation math */
  wheelRadius: number;
}

